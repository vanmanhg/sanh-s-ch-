export type LanguageCode = 'vi' | 'en' | 'zh' | 'km' | 'ja';

export interface LanguageOption {
  code: LanguageCode;
  label: string;
  flag: string;
  region: string;
  localeTag: string;
}

export const SUPPORTED_LANGUAGES: LanguageOption[] = [
  { code: 'vi', label: 'Tiếng Việt', flag: '🇻🇳', region: 'Việt Nam', localeTag: 'vi-VN' },
  { code: 'en', label: 'English', flag: '🇬🇧', region: 'Global', localeTag: 'en-US' },
  { code: 'zh', label: '中文 (简体)', flag: '🇨🇳', region: '中国 / 华人', localeTag: 'zh-CN' },
  { code: 'km', label: 'ភាសាខ្មែរ', flag: '🇰🇭', region: 'កម្ពុជា / Mekong', localeTag: 'km-KH' },
  { code: 'ja', label: '日本語', flag: '🇯🇵', region: '日本 / Smart Agri', localeTag: 'ja-JP' }
];

export const isSupportedLanguage = (val: unknown): val is LanguageCode => {
  return val === 'vi' || val === 'en' || val === 'zh' || val === 'km' || val === 'ja';
};

export const getLocaleTag = (lang: LanguageCode): string => {
  return SUPPORTED_LANGUAGES.find(l => l.code === lang)?.localeTag || 'vi-VN';
};

export const detectPreferredLanguage = (): LanguageCode => {
  try {
    const saved = localStorage.getItem('nongtro_lang');
    if (isSupportedLanguage(saved)) return saved;
  } catch {}

  try {
    if (typeof navigator !== 'undefined') {
      const candidates = [
        ...(Array.isArray(navigator.languages) ? navigator.languages : []),
        navigator.language
      ].filter(Boolean);

      for (const cand of candidates) {
        const prefix = cand.toLowerCase().split('-')[0];
        if (isSupportedLanguage(prefix)) {
          return prefix;
        }
      }
    }
  } catch {}

  return 'vi';
};

